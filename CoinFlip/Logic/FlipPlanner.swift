enum FlipPlanner {

    /// 决定这一次抛出的是日面还是月面。
    ///
    /// 这里只用系统自带的随机数，日月各 50%。
    /// ⚠️ 绝对不要为了让结果"看起来更均匀"而加任何平衡逻辑
    /// （比如"连续三次日面后强制出月面"）。
    /// 那样做恰恰破坏了五五开——真正的随机本来就会出现连续相同的结果。
    static func decideResult() -> CoinFace {
        Bool.random() ? .sun : .moon
    }
}
